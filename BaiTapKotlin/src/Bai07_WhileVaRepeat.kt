fun main() {
    var i : Int = 10
    //dùng while để có đk in ngược từ 10 về 1, count >0
    while (i >0) {
        println("Count $i")
        i--
    }

    //dùng repeat lặp lại 5 lần cố định
    repeat(5) {
        println("Dòng cố định in 5 lần.")
    }
}